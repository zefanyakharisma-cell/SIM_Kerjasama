drop view v_peta_mitra;
create view v_peta_mitra with (security_invoker = true) as
select n.id, n.nama, n.kode, n.latitude, n.longitude, n.is_domestic,
       count(distinct p.id)                     as jumlah_mitra,
       count(distinct pp.id_proposal_dokumen)   as jumlah_dokumen
  from negara n
  join partner p on p.id_negara = n.id and p.is_active
  left join partner_pengusul pp on pp.id_partner = p.id
 where n.latitude is not null and n.longitude is not null
 group by n.id, n.nama, n.kode, n.latitude, n.longitude, n.is_domestic;

comment on view v_peta_mitra is
  'Peta Mitra Global: one row per country that has at least one active partner.';

grant select on v_peta_mitra to authenticated;
